//! Numerical port of StarCellularLightArray, with column-major borrowed cells.
use std::mem::{align_of, size_of};
use std::panic::{catch_unwind, AssertUnwindSafe};
use std::slice;
use std::sync::atomic::{AtomicU64, Ordering};

// A receipt for integration tests: a linked symbol alone cannot prove the
// running WorldClient actually selected and executed this implementation.
static SUCCESSFUL_CALCULATIONS: AtomicU64 = AtomicU64::new(0);

#[no_mangle]
pub extern "C" fn star_lighting_call_count() -> u64 {
    SUCCESSFUL_CALCULATIONS.load(Ordering::Relaxed)
}

#[cfg(test)]
mod tests;

#[repr(C)]
#[derive(Clone, Copy, Debug)]
pub struct StarLightingParameters {
    pub spread_passes: u32,
    pub spread_max_air: f32,
    pub spread_max_obstacle: f32,
    pub point_max_air: f32,
    pub point_max_obstacle: f32,
    pub point_obstacle_boost: f32,
    pub point_additive: u32,
}
#[repr(C)]
#[derive(Clone, Copy, Debug, Default)]
pub struct StarLightingCell {
    pub light: [f32; 3],
    pub obstacle: u32,
}
#[repr(C)]
#[derive(Clone, Copy, Debug)]
pub struct StarLightingSpreadLight {
    pub position: [f32; 2],
    pub value: [f32; 3],
}
#[repr(C)]
#[derive(Clone, Copy, Debug)]
pub struct StarLightingPointLight {
    pub position: [f32; 2],
    pub value: [f32; 3],
    pub beam: f32,
    pub beam_angle: f32,
    pub beam_ambience: f32,
    pub as_spread: u32,
}

// Unlike f32::max/min, these retain std::max/min's operand ordering for NaNs
// generated by intermediate arithmetic. Finite inputs alone do not rule those out.
fn max(a: f32, b: f32) -> f32 {
    if a < b {
        b
    } else {
        a
    }
}
fn min(a: f32, b: f32) -> f32 {
    if b < a {
        b
    } else {
        a
    }
}
fn intensity(v: [f32; 3], n: usize) -> f32 {
    if n == 1 {
        v[0]
    } else {
        max(max(v[0], v[1]), v[2])
    }
}
fn subtract(mut v: [f32; 3], drop: f32, n: usize) -> [f32; 3] {
    if n == 1 {
        v[0] = max(v[0] - drop, 0.0);
    } else {
        let m = intensity(v, n);
        if m <= 0.0 {
            return v;
        }
        for c in &mut v {
            let d = (drop * *c) / m;
            *c = if *c > d { *c - d } else { 0.0 };
        }
    }
    v
}
fn spread(source: [f32; 3], mut dest: [f32; 3], mut drop: f32, n: usize) -> [f32; 3] {
    if n == 1 {
        dest[0] = max(source[0] - drop, dest[0]);
    } else {
        let m = max(source[0], max(source[1], source[2]));
        if m <= 0.0 {
            return dest;
        }
        drop /= m;
        for c in 0..3 {
            dest[c] = max(source[c] - source[c] * drop, dest[c]);
        }
    }
    dest
}

struct Array<'a> {
    width: usize,
    height: usize,
    n: usize,
    p: StarLightingParameters,
    cells: &'a mut [StarLightingCell],
}
impl Array<'_> {
    fn obstacle(&self, x: i64, y: i64) -> bool {
        // Wu's second antialias sample may leave the array even at valid endpoints.
        x >= 0
            && y >= 0
            && (x as usize) < self.width
            && (y as usize) < self.height
            && self.cells[x as usize * self.height + y as usize].obstacle != 0
    }
    fn sources(&mut self, lights: &[StarLightingSpreadLight]) {
        for light in lights {
            // Far-away sources have no samples in the grid; reject them before integer casts.
            if light.position[0] < -1.0
                || light.position[1] < -1.0
                || light.position[0] > self.width as f32 + 1.0
                || light.position[1] > self.height as f32 + 1.0
            {
                continue;
            }
            let x = (light.position[0] - 0.5).floor() as i64;
            let y = (light.position[1] - 0.5).floor() as i64;
            let xd = light.position[0] - x as f32 - 0.5;
            let yd = light.position[1] - y as f32 - 0.5;
            let att = 1.0
                / if self.obstacle(
                    light.position[0].floor() as i64,
                    light.position[1].floor() as i64,
                ) {
                    self.p.spread_max_obstacle
                } else {
                    self.p.spread_max_air
                };
            for (cx, cy, d) in [
                (x, y, 2.0 - (1.0 - xd) - (1.0 - yd)),
                (x, y + 1, 2.0 - (1.0 - xd) - yd),
                (x + 1, y, 2.0 - xd - (1.0 - yd)),
                (x + 1, y + 1, 2.0 - xd - yd),
            ] {
                if cx < 0 || cy < 0 || cx as usize >= self.width || cy as usize >= self.height {
                    continue;
                }
                let v = subtract(light.value, att * d, self.n);
                let cell = &mut self.cells[cx as usize * self.height + cy as usize];
                for (c, value) in v.iter().enumerate().take(self.n) {
                    cell.light[c] = max(cell.light[c], *value);
                }
            }
        }
    }
    fn sweeps(&mut self, bounds: [usize; 4]) {
        let [xmin, ymin, xmax, ymax] = bounds;
        let border = self.p.spread_max_air.ceil() as usize;
        let xmin = xmin.saturating_sub(border);
        let ymin = ymin.saturating_sub(border);
        let xmax = xmax.saturating_add(border).min(self.width);
        let ymax = ymax.saturating_add(border).min(self.height);
        if xmax <= xmin + 2 || ymax <= ymin + 2 {
            return;
        }
        let air = 1.0 / self.p.spread_max_air;
        let obs = 1.0 / self.p.spread_max_obstacle;
        // Constants::sqrt2 is double in C++; the reciprocal is rounded to float first.
        let air_diag = (air as f64 * std::f64::consts::SQRT_2) as f32;
        let obs_diag = (obs as f64 * std::f64::consts::SQRT_2) as f32;
        for _ in 0..self.p.spread_passes {
            for x in xmin + 1..xmax - 1 {
                for y in ymin + 1..ymax - 1 {
                    self.sweep_cell(x, y, true, air, obs, air_diag, obs_diag);
                }
            }
            for x in (xmin + 1..xmax - 1).rev() {
                for y in (ymin + 1..ymax - 1).rev() {
                    self.sweep_cell(x, y, false, air, obs, air_diag, obs_diag);
                }
            }
        }
    }
    #[allow(clippy::too_many_arguments)]
    fn sweep_cell(
        &mut self,
        x: usize,
        y: usize,
        forward: bool,
        air: f32,
        obs: f32,
        air_diag: f32,
        obs_diag: f32,
    ) {
        let source = self.cells[x * self.height + y];
        let (straight, diag) = if source.obstacle != 0 {
            (obs, obs_diag)
        } else {
            (air, air_diag)
        };
        let nx = if forward { x + 1 } else { x - 1 };
        let ny = if forward { y + 1 } else { y - 1 };
        for (dx, dy, d) in [
            (nx, y, straight),
            (x, ny, straight),
            (nx, y + 1, diag),
            (nx, y - 1, diag),
        ] {
            let cell = &mut self.cells[dx * self.height + dy];
            cell.light = spread(source.light, cell.light, d, self.n);
        }
    }
    fn line(&self, start: [f32; 2], end: [f32; 2], per: f32, limit: f32) -> f32 {
        let mut x1 = (start[0] as f64 - 0.5) as f32;
        let mut y1 = (start[1] as f64 - 0.5) as f32;
        let mut x2 = (end[0] as f64 - 0.5) as f32;
        let mut y2 = (end[1] as f64 - 0.5) as f32;
        let dx = x2 - x1;
        let dy = y2 - y1;
        let steep = dx.abs() < dy.abs();
        // Transposing axes leaves both endpoint and interior accumulation order intact.
        if steep {
            std::mem::swap(&mut x1, &mut y1);
            std::mem::swap(&mut x2, &mut y2);
        }
        if x2 < x1 {
            std::mem::swap(&mut x1, &mut x2);
            std::mem::swap(&mut y1, &mut y2);
        }
        let gradient = if steep { dx / dy } else { dy / dx };
        let obstacle = |x: i64, y: i64| {
            if steep {
                self.obstacle(y, x)
            } else {
                self.obstacle(x, y)
            }
        };
        let mut att = 0.0;
        let first = x1.round();
        let mut yend = y1 + gradient * (first - x1);
        // The original's unsuffixed 0.5 promotes these endpoint gaps to double.
        let gap_position = x1 as f64 + 0.5;
        let mut gap = (1.0 - (gap_position - gap_position.floor())) as f32;
        let mut yi = yend.floor() as i64;
        if obstacle(first as i64, yi) {
            att += (1.0 - (yend - yi as f32)) * gap * per;
        }
        if obstacle(first as i64, yi + 1) {
            att += (yend - yi as f32) * gap * per;
        }
        if att >= limit {
            return limit;
        }
        let mut inter = yend + gradient;
        let last = x2.round();
        yend = y2 + gradient * (last - x2);
        let gap_position = x2 as f64 + 0.5;
        gap = (gap_position - gap_position.floor()) as f32;
        yi = yend.floor() as i64;
        if obstacle(last as i64, yi) {
            att += (1.0 - (yend - yi as f32)) * gap * per;
        }
        if obstacle(last as i64, yi + 1) {
            att += (yend - yi as f32) * gap * per;
        }
        if att >= limit {
            return limit;
        }
        for x in first as i64 + 1..last as i64 {
            let yi = inter.floor() as i64;
            let fraction = inter - yi as f32;
            if obstacle(x, yi) {
                att += (1.0 - fraction) * per;
            }
            if obstacle(x, yi + 1) {
                att += fraction * per;
            }
            if att >= limit {
                return limit;
            }
            inter += gradient;
        }
        min(att, limit)
    }
    fn points(&mut self, lights: &[StarLightingPointLight], bounds: [usize; 4]) {
        let [xmin, ymin, xmax, ymax] = bounds;
        let point_obs = 1.0 / self.p.point_max_obstacle;
        let point_air = 1.0 / self.p.point_max_air;
        for light in lights {
            let [px, py] = light.position;
            if px < 0.0 || px > (self.width - 1) as f32 || py < 0.0 || py > (self.height - 1) as f32
            {
                continue;
            }
            let max_intensity = intensity(light.value, self.n);
            let beam_direction = [light.beam_angle.cos(), light.beam_angle.sin()];
            let as_spread = light.as_spread != 0;
            let per_obs = if as_spread {
                1.0 / self.p.spread_max_obstacle
            } else {
                point_obs
            };
            let per_air = if as_spread {
                1.0 / self.p.spread_max_air
            } else {
                point_air
            };
            let range = max_intensity
                * if as_spread {
                    self.p.spread_max_air
                } else {
                    self.p.point_max_air
                };
            let lxmin = max(xmin as f32, px - range).floor() as usize;
            let lymin = max(ymin as f32, py - range).floor() as usize;
            let lxmax = (min(xmax as f32, px + range).ceil() as usize).min(self.width);
            let lymax = (min(ymax as f32, py + range).ceil() as usize).min(self.height);
            for x in lxmin..lxmax {
                for y in lymin..lymax {
                    let index = x * self.height + y;
                    let old = self.cells[index].light;
                    let block = [x as f32 + 0.5, y as f32 + 0.5];
                    let relative = [block[0] - px, block[1] - py];
                    let distance =
                        ((0.0 + relative[0] * relative[0]) + relative[1] * relative[1]).sqrt();
                    // This branch intentionally adds even in max mode, without hybrid scaling.
                    if distance == 0.0 {
                        for c in 0..self.n {
                            self.cells[index].light[c] = light.value[c] + old[c];
                        }
                        continue;
                    }
                    let mut attenuation = distance * per_air;
                    if attenuation >= 1.0 {
                        continue;
                    }
                    let direction = [relative[0] / distance, relative[1] / distance];
                    if light.beam > if self.n == 1 { 0.0001 } else { 0.0 } {
                        let dot = (0.0 + direction[0] * beam_direction[0])
                            + direction[1] * beam_direction[1];
                        attenuation += (1.0 - light.beam_ambience)
                            * min(max(light.beam * (1.0 - dot), 0.0), 1.0);
                        if attenuation >= 1.0 {
                            continue;
                        }
                    }
                    let remaining = max_intensity - attenuation;
                    if remaining <= 0.0 {
                        continue;
                    }
                    let circular = per_obs / max(direction[0].abs(), direction[1].abs());
                    let blocked = self.line(block, light.position, circular, remaining);
                    attenuation += blocked;
                    if !as_spread {
                        attenuation += min(blocked, circular) * self.p.point_obstacle_boost;
                    }
                    if attenuation < 1.0 {
                        let value = subtract(light.value, attenuation, self.n);
                        if self.p.point_additive != 0 {
                            if intensity(value, self.n) > 0.0001 {
                                for c in 0..self.n {
                                    self.cells[index].light[c] =
                                        old[c] + if as_spread { value[c] * 0.15 } else { value[c] };
                                }
                            }
                        } else {
                            for c in 0..self.n {
                                self.cells[index].light[c] = max(value[c], old[c]);
                            }
                        }
                    }
                }
            }
        }
    }
}
fn region<T>(ptr: *const T, len: usize) -> Option<(usize, usize)> {
    if len == 0 {
        return Some((0, 0));
    }
    if ptr.is_null() || (ptr as usize) % align_of::<T>() != 0 {
        return None;
    }
    let bytes = len.checked_mul(size_of::<T>())?;
    if bytes > isize::MAX as usize {
        return None;
    }
    Some((ptr as usize, (ptr as usize).checked_add(bytes)?))
}
fn overlaps(a: (usize, usize), b: (usize, usize)) -> bool {
    a.0 < b.1 && b.0 < a.1
}
unsafe fn borrowed<'a, T>(ptr: *const T, len: usize) -> &'a [T] {
    if len == 0 {
        &[]
    } else {
        slice::from_raw_parts(ptr, len)
    }
}

/// Executes the frozen StarRustLighting.h ABI; returns 0, invalid arguments (1), or caught panic (2).
///
/// # Safety
/// Nonempty pointers must designate initialized allocations of the declared sizes, valid for
/// this call. Cells must be writable and exclusively borrowed. Numeric pointer checks cannot
/// establish allocation provenance or protect against concurrent writes by foreign code.
#[no_mangle]
#[allow(clippy::too_many_arguments)]
pub unsafe extern "C" fn star_lighting_calculate(
    channels: u32,
    width: usize,
    height: usize,
    parameters: *const StarLightingParameters,
    cells: *mut StarLightingCell,
    cells_len: usize,
    spread_lights: *const StarLightingSpreadLight,
    spread_len: usize,
    point_lights: *const StarLightingPointLight,
    point_len: usize,
    x_min: usize,
    y_min: usize,
    x_max: usize,
    y_max: usize,
) -> i32 {
    catch_unwind(AssertUnwindSafe(|| {
        if !matches!(channels, 1 | 3)
            || width == 0
            || height == 0
            || width > i32::MAX as usize
            || height > i32::MAX as usize
            || width.checked_mul(height) != Some(cells_len)
            || x_min > x_max
            || y_min > y_max
            || x_max > width
            || y_max > height
        {
            return 1;
        }
        let Some(cr) = region(cells, cells_len) else {
            return 1;
        };
        let Some(pr) = region(parameters, 1) else {
            return 1;
        };
        let Some(sr) = region(spread_lights, spread_len) else {
            return 1;
        };
        let Some(lr) = region(point_lights, point_len) else {
            return 1;
        };
        if overlaps(cr, pr) || overlaps(cr, sr) || overlaps(cr, lr) {
            return 1;
        }
        let p = *parameters;
        let distances = [
            p.spread_max_air,
            p.spread_max_obstacle,
            p.point_max_air,
            p.point_max_obstacle,
        ];
        if distances.iter().any(|d| !d.is_finite() || *d <= 0.0)
            || !p.point_obstacle_boost.is_finite()
        {
            return 1;
        }
        let spread = borrowed(spread_lights, spread_len);
        let points = borrowed(point_lights, point_len);
        if spread.iter().any(|l| {
            l.position
                .iter()
                .chain(l.value.iter())
                .any(|v| !v.is_finite())
        }) || points.iter().any(|l| {
            l.position
                .iter()
                .chain(l.value.iter())
                .chain([&l.beam, &l.beam_angle, &l.beam_ambience])
                .any(|v| !v.is_finite())
        }) {
            return 1;
        }
        let cells = slice::from_raw_parts_mut(cells, cells_len);
        if cells.iter().any(|c| c.light.iter().any(|v| !v.is_finite())) {
            return 1;
        }
        let mut array = Array {
            width,
            height,
            n: channels as usize,
            p,
            cells,
        };
        let bounds = [x_min, y_min, x_max, y_max];
        array.sources(spread);
        array.sweeps(bounds);
        array.points(points, bounds);
        SUCCESSFUL_CALCULATIONS.fetch_add(1, Ordering::Relaxed);
        0
    }))
    .unwrap_or(2)
}
